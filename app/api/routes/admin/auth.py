def _is_production() -> bool:
    return (
        str(settings.app_environment)
        .strip()
        .lower()
        == "production"
    )


def _client_ip(
    request: Request,
) -> str | None:
    """
    Use the direct socket peer address.

    X-Forwarded-For is intentionally not trusted here.
    Production proxy trust must be configured explicitly at
    the deployment boundary.
    """

    if request.client is None:
        return None

    return request.client.host


def _request_id(
    request: Request,
) -> str | None:
    """
    Return the trusted request correlation ID generated by
    RequestContextMiddleware.

    Do not accept a client-supplied request ID here.
    """

    value = getattr(
        request.state,
        "request_id",
        None,
    )

    if not isinstance(
        value,
        str,
    ):
        return None

    normalized = (
        value.strip()
    )

    return normalized or None


def _user_agent(
    request: Request,
) -> str | None:
    return request.headers.get(
        "user-agent"
    )


async def _record_denied_auth_event(
    db: AsyncSession,
    *,
    request: Request,
    action: AuditAction,
    reason: str,
    admin: Admin | None = None,
    admin_session_id: UUID | None = None,
    metadata: Mapping[
        str,
        Any,
    ]
    | None = None,
) -> None:
    """
    Persist an authentication/security denial after the caller
    has rolled back the failed protected operation.

    Authentication credentials, session tokens, CSRF tokens,
    identity assertions and other secrets must never be placed
    in audit metadata.
    """

    event_metadata: dict[
        str,
        Any,
    ] = {
        "reason": reason,
    }

    if metadata is not None:
        event_metadata.update(
            dict(metadata)
        )

    await record_audit_event(
        db,
        actor_type=(
            ActorType.ADMIN.value
            if admin is not None
            else ActorType.SYSTEM.value
        ),
        actor_id=(
            str(admin.id)
            if admin is not None
            else None
        ),
        action=action.value,
        metadata=event_metadata,
        ip_address=_client_ip(
            request
        ),
        admin_session_id=(
            admin_session_id
        ),
        request_id=_request_id(
            request
        ),
        user_agent=_user_agent(
            request
        ),
        outcome="failure",
    )

    await db.commit()


async def _persist_invalid_admin_session(
    db: AsyncSession,
    *,
    request: Request,
    exc: InvalidAdminSessionError,
) -> None:
    """
    Persist automatic administrator-session invalidation after
    the failed validation transaction has been rolled back.

    Revocation and the corresponding audit event are committed
    atomically.

    Only safe persistent identifiers and reason codes from the
    validation exception are used. Raw session credentials are
    never logged or persisted here.
    """

    if not exc.requires_revocation:
        return

    if (
        exc.admin_id is None
        or exc.admin_session_id is None
    ):
        return

    reason = (
        exc.reason
        or "security_state_changed"
    )

    await revoke_admin_session_by_id(
        db,
        admin_session_id=(
            exc.admin_session_id
        ),
        admin_id=(
            exc.admin_id
        ),
        reason=reason,
    )

    if reason == "absolute_expiry":
        action = (
            AuditAction
            .ADMIN_SESSION_EXPIRED
        )

    elif reason == "idle_timeout":
        action = (
            AuditAction
            .ADMIN_SESSION_IDLE_EXPIRED
        )

    else:
        action = (
            AuditAction
            .ADMIN_SESSION_SECURITY_INVALIDATED
        )

    await record_audit_event(
        db,
        actor_type=ActorType.ADMIN.value,
        actor_id=str(
            exc.admin_id
        ),
        action=action.value,
        metadata={
            "reason": reason,
        },
        ip_address=_client_ip(
            request
        ),
        admin_session_id=(
            exc.admin_session_id
        ),
        request_id=_request_id(
            request
        ),
        user_agent=_user_agent(
            request
        ),
        outcome="failure",
    )

    await db.commit()


def _set_admin_cookies(
    response: Response,
    *,
    created: CreatedAdminSession,
) -> None:
    """
    Set the server-managed authentication cookie and the
    separate browser-readable CSRF cookie.
    """

    secure = bool(
        settings.cookie_secure
    )

    if _is_production():
        secure = True

    session_cookie_name = (
        get_admin_session_cookie_name()
    )

    csrf_cookie_name = (
        get_admin_csrf_cookie_name()
    )

    # --------------------------------------------------------
    # Authentication credential
    # --------------------------------------------------------
    #
    # Raw administrator session token:
    #
    # - HttpOnly
    # - Secure in production
    # - SameSite=Lax
    # - Path=/
    # - no Domain
    #
    # The raw value is never stored in PostgreSQL.
    #

    response.set_cookie(
        key=session_cookie_name,
        value=created.raw_token,
        max_age=(
            settings
            .admin_session_absolute_lifetime_seconds
        ),
        httponly=True,
        secure=secure,
        samesite="lax",
        path="/",
    )

    # --------------------------------------------------------
    # CSRF credential
    # --------------------------------------------------------
    #
    # This value is intentionally readable by frontend
    # JavaScript because the frontend must echo it in the
    # X-Admin-CSRF-Token header.
    #
    # It is NOT an authentication credential.
    #

    response.set_cookie(
        key=csrf_cookie_name,
        value=created.csrf_token,
        max_age=(
            settings
            .admin_session_absolute_lifetime_seconds
        ),
        httponly=False,
        secure=secure,
        samesite="lax",
        path="/",
    )


def _clear_admin_cookies(
    response: Response,
) -> None:
    """
    Remove both administrator browser cookies.
    """

    secure = bool(
        settings.cookie_secure
    )

    if _is_production():
        secure = True

    response.delete_cookie(
        key=(
            get_admin_session_cookie_name()
        ),
        path="/",
        secure=secure,
        httponly=True,
        samesite="lax",
    )

    response.delete_cookie(
        key=(
            get_admin_csrf_cookie_name()
        ),
        path="/",
        secure=secure,
        httponly=False,
        samesite="lax",
    )


def _admin_payload(
    admin: Admin,
) -> dict[str, object]:
    """
    Safe administrator representation returned to the
    authenticated frontend.

    Do not expose auth_subject or authentication secrets.
    """

    return {
        "id": str(admin.id),
        "email": admin.email,
        "display_name": (
            admin.display_name
        ),
        "role": admin.role.value,
    }


