@router.post(
    "/session",
    status_code=(
        status.HTTP_201_CREATED
    ),
)
async def establish_admin_session(
    request: Request,
    response: Response,
    db: DatabaseSession,
    credentials: BearerCredentials,
    cloudflare_access_assertion: Annotated[
        str | None,
        Header(
            alias=(
                "Cf-Access-Jwt-Assertion"
            ),
        ),
    ] = None,
) -> dict[str, object]:
    """
    Exchange an externally authenticated administrator
    identity for a BAKABOOST server-managed session.

    Production authentication requires a cryptographically
    validated Cloudflare Access application JWT supplied in
    Cf-Access-Jwt-Assertion.

    The Authorization Bearer mechanism is accepted only by
    the explicitly enabled local-development authentication
    mode.

    External authentication alone never grants local
    administrator authorization. The immutable external
    subject must match an explicitly provisioned and active
    local Admin row.

    Ordinary Cloudflare Access application JWTs do not prove
    that a fresh MFA ceremony occurred at session creation.

    Therefore this endpoint creates only baseline local
    administrator assurance. Sensitive operations remain
    fail-closed until the dedicated step-up flow succeeds.
    """

    environment = (
        str(settings.app_environment)
        .strip()
        .lower()
    )

    development_auth = (
        environment == "development"
        and settings
        .dev_admin_auth_enabled
    )

    raw_assertion: str | None = None
    auth_method: str

    # --------------------------------------------------------
    # Resolve external authentication assertion
    # --------------------------------------------------------

    if development_auth:
        if credentials is not None:
            candidate = (
                credentials
                .credentials
                .strip()
            )

            if candidate:
                raw_assertion = (
                    candidate
                )

        auth_method = "development"

        if raw_assertion is None:
            await (
                _record_denied_auth_event(
                    db,
                    request=request,
                    action=(
                        AuditAction
                        .ADMIN_AUTH_DENIED
                    ),
                    reason=(
                        "missing_development_"
                        "credentials"
                    ),
                )
            )

            raise HTTPException(
                status_code=(
                    status
                    .HTTP_401_UNAUTHORIZED
                ),
                detail=(
                    "Authentication required."
                ),
                headers={
                    "WWW-Authenticate": (
                        "Bearer"
                    ),
                },
            )

    else:
        if isinstance(
            cloudflare_access_assertion,
            str,
        ):
            candidate = (
                cloudflare_access_assertion
                .strip()
            )

            if candidate:
                raw_assertion = (
                    candidate
                )

        auth_method = (
            "cloudflare_access"
        )

        if raw_assertion is None:
            await (
                _record_denied_auth_event(
                    db,
                    request=request,
                    action=(
                        AuditAction
                        .ADMIN_AUTH_DENIED
                    ),
                    reason=(
                        "missing_cloudflare_"
                        "access_assertion"
                    ),
                )
            )

            raise HTTPException(
                status_code=(
                    status
                    .HTTP_401_UNAUTHORIZED
                ),
                detail=(
                    "Authentication required."
                ),
            )

    admin: Admin | None = None
    created: (
        CreatedAdminSession
        | None
    ) = None

    try:
        # ----------------------------------------------------
        # Cryptographically verify external identity
        # ----------------------------------------------------

        identity = (
            decode_admin_token(
                raw_assertion
            )
        )

        # ----------------------------------------------------
        # Exact local administrator binding
        # ----------------------------------------------------

        admin = (
            await get_admin_for_identity(
                db,
                identity=identity,
            )
        )

        now = datetime.now(
            UTC
        )

        # ----------------------------------------------------
        # Normal session establishment does not fabricate MFA
        # assurance.
        # ----------------------------------------------------

        created = (
            await create_admin_session(
                db,
                admin=admin,
                authenticated_at=now,
                mfa_verified_at=None,
                phishing_resistant_verified_at=(
                    None
                ),
                auth_method=auth_method,
                ip_address=(
                    _client_ip(
                        request
                    )
                ),
                user_agent=(
                    _user_agent(
                        request
                    )
                ),
            )
        )

        # ----------------------------------------------------
        # Audit authentication
        # ----------------------------------------------------

        await record_audit_event(
            db,
            actor_type=(
                ActorType.ADMIN.value
            ),
            actor_id=str(
                admin.id
            ),
            action=(
                AuditAction
                .ADMIN_AUTH_SUCCEEDED
                .value
            ),
            metadata={
                "auth_method": (
                    auth_method
                ),
                "mfa_verified": False,
                "phishing_resistant_mfa": (
                    False
                ),
            },
            ip_address=_client_ip(
                request
            ),
            admin_session_id=(
                created.session.id
            ),
            request_id=_request_id(
                request
            ),
            user_agent=_user_agent(
                request
            ),
            outcome="success",
        )

        # ----------------------------------------------------
        # Audit session creation
        # ----------------------------------------------------

        await record_audit_event(
            db,
            actor_type=(
                ActorType.ADMIN.value
            ),
            actor_id=str(
                admin.id
            ),
            action=(
                AuditAction
                .ADMIN_SESSION_CREATED
                .value
            ),
            metadata={
                "auth_method": (
                    auth_method
                ),
            },
            ip_address=_client_ip(
                request
            ),
            admin_session_id=(
                created.session.id
            ),
            request_id=_request_id(
                request
            ),
            user_agent=_user_agent(
                request
            ),
            outcome="success",
        )

        await db.commit()

    except AdminAuthenticationError as exc:
        await db.rollback()

        await _record_denied_auth_event(
            db,
            request=request,
            action=(
                AuditAction
                .ADMIN_AUTH_DENIED
            ),
            reason=(
                "authentication_denied"
            ),
            admin=admin,
        )

        response_headers: (
            dict[str, str]
            | None
        ) = None

        if development_auth:
            response_headers = {
                "WWW-Authenticate": (
                    "Bearer"
                ),
            }

        raise HTTPException(
            status_code=(
                status
                .HTTP_401_UNAUTHORIZED
            ),
            detail=(
                "Invalid administrator "
                "authentication."
            ),
            headers=(
                response_headers
            ),
        ) from exc

    except AdminSessionError as exc:
        await db.rollback()

        await _record_denied_auth_event(
            db,
            request=request,
            action=(
                AuditAction
                .ADMIN_AUTH_DENIED
            ),
            reason=(
                "session_establishment_"
                "failed"
            ),
            admin=admin,
        )

        raise HTTPException(
            status_code=(
                status
                .HTTP_401_UNAUTHORIZED
            ),
            detail=(
                "Unable to establish "
                "administrator session."
            ),
        ) from exc

    if (
        admin is None
        or created is None
    ):
        raise RuntimeError(
            "Administrator session creation "
            "completed without required "
            "result state."
        )

    # --------------------------------------------------------
    # Browser credentials are issued only after commit.
    # --------------------------------------------------------

    _set_admin_cookies(
        response,
        created=created,
    )

    response.headers[
        "Cache-Control"
    ] = "no-store"

    return {
        "authenticated": True,
        "admin": (
            _admin_payload(
                admin
            )
        ),
        "expires_at": (
            created
            .session
            .expires_at
            .isoformat()
        ),
        "csrf_token": (
            created.csrf_token
        ),
    }


