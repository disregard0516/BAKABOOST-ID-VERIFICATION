@router.delete(
    "/session",
    status_code=(
        status.HTTP_204_NO_CONTENT
    ),
)
async def destroy_admin_session(
    request: Request,
    response: Response,
    db: DatabaseSession,
    admin_session_token: Annotated[
        str | None,
        Cookie(
            alias=(
                get_admin_session_cookie_name()
            ),
        ),
    ] = None,
    csrf_cookie: Annotated[
        str | None,
        Cookie(
            alias=(
                get_admin_csrf_cookie_name()
            ),
        ),
    ] = None,
    csrf_header: Annotated[
        str | None,
        Header(
            alias=(
                settings
                .admin_csrf_header_name
            ),
        ),
    ] = None,
) -> Response:
    """
    Revoke the current administrator session.

    Logout is CSRF-protected when an authenticated session
    exists.
    """

    if not admin_session_token:
        _clear_admin_cookies(
            response
        )

        response.status_code = (
            status
            .HTTP_204_NO_CONTENT
        )

        return response

    validated = None

    try:
        validated = (
            await get_valid_admin_session(
                db,
                raw_token=(
                    admin_session_token
                ),
                touch=False,
            )
        )

        validate_admin_session_csrf(
            validated.session,
            cookie_token=(
                csrf_cookie
            ),
            header_token=(
                csrf_header
            ),
        )

        await revoke_admin_session(
            db,
            admin_session=(
                validated.session
            ),
            reason="logout",
        )

        await record_audit_event(
            db,
            actor_type=(
                ActorType.ADMIN.value
            ),
            actor_id=str(
                validated.admin.id
            ),
            action=(
                AuditAction
                .ADMIN_SESSION_REVOKED
                .value
            ),
            metadata={
                "reason": "logout",
            },
            ip_address=_client_ip(
                request
            ),
            admin_session_id=(
                validated.session.id
            ),
            request_id=_request_id(
                request
            ),
            user_agent=_user_agent(
                request
            ),
            outcome="success",
        )

        await db.commit()

    except InvalidAdminSessionError as exc:
        await db.rollback()

        if validated is not None:
            await _record_denied_auth_event(
                db,
                request=request,
                action=(
                    AuditAction
                    .ADMIN_CSRF_DENIED
                ),
                reason=(
                    exc.reason
                    or "csrf_validation_failed"
                ),
                admin=(
                    validated.admin
                ),
                admin_session_id=(
                    validated.session.id
                ),
            )

        elif exc.requires_revocation:
            await (
                _persist_invalid_admin_session(
                    db,
                    request=request,
                    exc=exc,
                )
            )

        else:
            await _record_denied_auth_event(
                db,
                request=request,
                action=(
                    AuditAction
                    .ADMIN_AUTH_DENIED
                ),
                reason=(
                    exc.reason
                    or "invalid_admin_session"
                ),
            )

        raise HTTPException(
            status_code=(
                status
                .HTTP_403_FORBIDDEN
            ),
            detail=(
                "Invalid request "
                "verification."
            ),
        ) from exc

    except AdminSessionError as exc:
        await db.rollback()

        await _record_denied_auth_event(
            db,
            request=request,
            action=(
                AuditAction
                .ADMIN_AUTH_DENIED
            ),
            reason=(
                "session_revocation_failed"
            ),
            admin=(
                validated.admin
                if validated
                is not None
                else None
            ),
            admin_session_id=(
                validated.session.id
                if validated
                is not None
                else None
            ),
        )

        raise HTTPException(
            status_code=(
                status
                .HTTP_403_FORBIDDEN
            ),
            detail=(
                "Invalid request "
                "verification."
            ),
        ) from exc

    _clear_admin_cookies(
        response
    )

    response.status_code = (
        status.HTTP_204_NO_CONTENT
    )

    return response